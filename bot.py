def update_stats(
    user_id,
    correct,
    questions,
    score,
):

    conn = sqlite3.connect(DB)

    row = conn.execute(
        """
        SELECT games, correct, questions, best_score
        FROM players
        WHERE user_id=?
        """,
        (user_id,),
    ).fetchone()

    games = row[0] + 1
    total_correct = row[1] + correct
    total_questions = row[2] + questions
    best_score = max(row[3], score)

    conn.execute(
        """
        UPDATE players
        SET
            games=?,
            correct=?,
            questions=?,
            best_score=?
        WHERE user_id=?
        """,
        (
            games,
            total_correct,
            total_questions,
            best_score,
            user_id,
        ),
    )

    conn.commit()
    conn.close()


