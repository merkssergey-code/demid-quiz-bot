async def send_question(
    callback,
    user_id,
    prefix="",
):

    game = games[user_id]

    question = game["questions"][
        game["current"]
    ]

    number = game["current"] + 1

    total = len(game["questions"])

    category = CATEGORY_NAMES[
        game["category"]
    ]

    text = ""

    if prefix:
        text += f"{prefix}\n\n"

    text += (
        f"<b>{category}</b>\n\n"
        f"вќ“ <b>Р’РѕРїСЂРѕСЃ {number}/{total}</b>\n\n"
        f"{question['q']}\n\n"
        f"в­ђ РћС‡РєРё: {game['score']}"
    )

    chat_id = callback.message.chat.id

    try:
        await callback.message.delete()
    except Exception:
        pass

    img = question.get("img")

    if img:

        await bot.send_photo(
            chat_id,
            photo=img,
            caption=text,
            reply_markup=answer_keyboard(question),
        )

    else:

        await bot.send_message(
            chat_id,
            text,
            reply_markup=answer_keyboard(question),
        )

    game["asked_at"] = time.monotonic()


